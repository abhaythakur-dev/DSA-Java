public class ForEachLoop {
    public static void main(String[] args) {
    
// For Each Loop:- Used to traverse Data Structures Like(Array,Hashmap,Hashset)
// Cannot modify Array Element 

        int[] arr = {5,4,5,3,6};
        for(int ele : arr){
            System.out.println(ele+" ");
        }

    }

    
}
